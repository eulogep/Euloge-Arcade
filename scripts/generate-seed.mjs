// Generates supabase/seed.sql from the bootstrap JSON files in src/data.
// The JSON files are only used to bootstrap a fresh database (and as the catalog
// in "local mode" when no backend is configured). Once the database exists, it is
// the single source of truth and the catalog is edited from the admin space.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const domains = read('src/data/embed-domains.seed.json');
const games = read('src/data/games.seed.json');
const achievements = read('src/data/achievements.seed.json');

const out = [];
out.push('-- AUTO-GENERATED by scripts/generate-seed.mjs — do not edit by hand.');
out.push('-- Bootstrap data for a fresh database. Re-running is idempotent.\n');

out.push('insert into public.embed_domains (domain, note) values');
out.push(domains.map((d) => `  (${q(d.domain)}, ${q(d.note)})`).join(',\n'));
out.push('on conflict (domain) do nothing;\n');

const cols = [
  'id', 'slug', 'title', 'tagline', 'description', 'instructions', 'genre', 'cover_url', 'banner_url',
  'launch_mode', 'launch_url', 'source_url', 'developer', 'license_status', 'license_notes',
  'compatibility', 'controls', 'orientation', 'featured', 'featured_rank', 'supports_scores',
  'status', 'published_at', 'created_at',
];
out.push(`insert into public.games (${cols.join(', ')}) values`);
out.push(
  games
    .map((g) => {
      const vals = cols.map((c) => {
        if (c === 'genre') return arr(g.genre);
        if (c === 'compatibility' || c === 'controls') return json(g[c]);
        if (c === 'launch_mode') return `${q(g[c])}::public.launch_mode`;
        if (c === 'license_status') return `${q(g[c])}::public.license_status`;
        if (c === 'status') return `${q(g[c])}::public.game_status`;
        return q(g[c]);
      });
      return `  (${vals.join(', ')})`;
    })
    .join(',\n'),
);
out.push('on conflict (id) do nothing;\n');

out.push('insert into public.achievements (id, title, description, icon, game_id, sort) values');
out.push(
  achievements
    .map((a) => {
      const gameId = a.game_slug ? `(select id from public.games where slug = ${q(a.game_slug)})` : 'null';
      return `  (${q(a.id)}, ${q(a.title)}, ${q(a.description)}, ${q(a.icon)}, ${gameId}, ${a.sort})`;
    })
    .join(',\n'),
);
out.push('on conflict (id) do update set title = excluded.title, description = excluded.description, icon = excluded.icon, sort = excluded.sort;\n');

writeFileSync(resolve(root, 'supabase/seed.sql'), out.join('\n'));
console.log(`seed.sql: ${domains.length} domains, ${games.length} games, ${achievements.length} achievements`);
